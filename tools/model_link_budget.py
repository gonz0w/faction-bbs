#!/usr/bin/env python3
"""Count synthetic payloads and model serialized exchanges; never run a network test."""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FIXTURE = ROOT / 'dev-docs/research/fixtures/003-workloads.json'
REPORT = ROOT / 'dev-docs/research/0003-link-budget-results.md'


def integer(value, name, *, minimum=0):
    if type(value) is not int or value < minimum:
        raise ValueError(f'{name} must be an integer >= {minimum}')
    return value


def payload_totals(workload):
    turns = workload['exchanges']
    if not isinstance(turns, list) or not turns:
        raise ValueError('A workload needs at least one sequential exchange')
    up = down = 0
    for turn in turns:
        # ASCII is a fixture condition, not a selected product encoding.
        up += len(turn['client'].encode('ascii')) + integer(turn['client_payload_bytes'], 'client payload')
        down += len(turn['server'].encode('ascii')) + integer(turn['server_payload_bytes'], 'server payload')
    return up, down, len(turns)


def modeled_seconds(up, down, turns, profile):
    integer(up, 'uploaded bytes')
    integer(down, 'downloaded bytes')
    integer(turns, 'sequential exchanges')
    up_rate = integer(profile['up_bps'], 'uplink bit/s', minimum=1)
    down_rate = integer(profile['down_bps'], 'downlink bit/s', minimum=1)
    rtt = integer(profile['rtt_ms'], 'nominal RTT ms')
    return 8 * up / up_rate + 8 * down / down_rate + turns * rtt / 1000


def stream_load(stream, profile):
    bits = integer(stream['record_bytes'], 'record bytes') * integer(stream['records_per_second'], 'records/s') * 8
    rate = integer(profile['down_bps'], 'downlink bit/s', minimum=1)
    return bits, bits / rate


def render(raw):
    data = json.loads(raw)
    if data['schema_version'] != 1:
        raise ValueError('Unsupported workload fixture schema')
    for group in ['profiles', 'workloads', 'inbound_streams']:
        ids = [item['id'] for item in data[group]]
        if not ids or len(set(ids)) != len(ids):
            raise ValueError(f'{group} must have unique non-empty IDs')
    profiles = data['profiles']
    lines = ['# Synthetic application-payload model — issue #3', '',
        'Generated by `python3 tools/model_link_budget.py --write`. Verify with `--check`.', '',
        'Fixture: [003-workloads.json](fixtures/003-workloads.json). SHA-256: `' + hashlib.sha256(raw).hexdigest() + '`.', '',
        '**Analytical results only.** These are counted fixture bytes and arithmetic, not measured BBS/network performance, production budgets, or supported-network claims.', '',
        'Each exchange is modeled serially: `8*upload_bytes/up_bps + 8*download_bytes/down_bps + exchanges*nominal_RTT_seconds`. Human think time, connection/authentication handshakes, protocol/framing/encryption, compression, server time, queuing, retransmissions, jitter, loss, and outages are excluded. Full-duplex overlap or pipelining is not represented. Sized payload blocks are declared stand-ins, not actual files or game traces.', '',
        'P3 uses the P2 connected-state arithmetic only. Its outage behavior is not modeled: times below must never be read as interruption/recovery results. See the [journey report](0003-constrained-user-journeys.md) for the separate failure experiments.', '',
        '| Workload | Up bytes | Down bytes | Sequential exchanges | ' + ' | '.join(p['id'] + (' connected-only seconds' if p['outage_seconds'] else ' modeled seconds') for p in profiles) + ' |',
        '| --- | ---: | ---: | ---: | ' + ' | '.join('---:' for _ in profiles) + ' |']
    for workload in data['workloads']:
        up, down, turns = payload_totals(workload)
        values = [f'{modeled_seconds(up, down, turns, profile):.3f}' for profile in profiles]
        lines.append(f"| {workload['id']} | {up} | {down} | {turns} | " + ' | '.join(values) + ' |')
    lines += ['', '## Hypothetical inbound chat load', '',
        'One stream, server-to-client only; record sizes exclude transport overhead. Ratios at or above 1 exceed or consume the entire nominal direction capacity before other traffic. No queue/drop/backpressure behavior has been simulated.', '',
        '| Stream | Payload bit/s | ' + ' | '.join(p['id'] + ' capacity ratio' for p in profiles) + ' |',
        '| --- | ---: | ' + ' | '.join('---:' for _ in profiles) + ' |']
    for stream in data['inbound_streams']:
        bits, _ = stream_load(stream, profiles[0])
        ratios = [f'{stream_load(stream, p)[1]:.4f}' for p in profiles]
        lines.append(f"| {stream['id']} | {bits} | " + ' | '.join(ratios) + ' |')
    lines += ['', 'Changing fixture text, declared blocks, profiles, or stream assumptions changes this report. Review the assumptions; passing a reproducibility check establishes no runtime capability.']
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument('--write', action='store_true', help='Regenerate the checked-in analytical report')
    mode.add_argument('--check', action='store_true', help='Fail if the checked-in report is stale')
    args = parser.parse_args()
    result = render(FIXTURE.read_bytes())
    if args.check:
        if not REPORT.is_file() or REPORT.read_text() != result:
            parser.exit(1, 'Synthetic payload report is stale; run tools/model_link_budget.py --write\n')
        print('Synthetic payload report matches fixture arithmetic; no network/runtime test was performed.')
    elif args.write:
        REPORT.write_text(result)
        print('Wrote the synthetic payload arithmetic report; no network/runtime test was performed.')
    else:
        print(result, end='')


if __name__ == '__main__':
    main()
